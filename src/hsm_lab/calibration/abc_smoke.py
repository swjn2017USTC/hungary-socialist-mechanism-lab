"""P05 ABC API smoke (plan §271).

Two distinct proofs, neither of which is historical-calibration evidence:

1. ``abc_synthetic_recovery`` runs the *real* kernel against a throwaway
   synthetic target generated by the same kernel at one known structural
   parameter value. It exists only to prove the inference API works: particles
   are sampled, populations advance, the run stops on its budget, no checkpoint
   is used and independent seeds repeat. The synthetic target is not a
   historical artifact and never enters DATA_MANIFEST.
2. ``abc_registry_path`` runs the candidate-discovery step against the real
   registry and must return ``NO_IDENTIFIABLE_PARAMETERS``; it proves the
   pipeline does not invent a candidate set when nothing is identifiable.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from hsm_lab.calibration.screen import screen_parameters

# The single structural parameter the synthetic recovery is allowed to move: a
# declared MaterialParameters scalar that changes real production behaviour.
PROBE_PARAMETER = "utilization"
PROBE_LO, PROBE_HI = 0.5, 1.0


def _summary_output(
    theta: float, *, root: Path, ticks: int, households: int, scenario: str
) -> float:
    """Realized output summed over the run (read from the kernel's own tallies)."""
    from hsm_lab.contract.guards import load_research_contract, load_scenario
    from hsm_lab.contract.schemas import OutputPolicy
    from hsm_lab.data.registry import DataRegistry
    from hsm_lab.engine.material import run_material

    contract = load_research_contract(root)
    base = load_scenario(root, scenario)
    spec = base.model_copy(
        update={
            "households": households,
            "ticks": ticks,
            "output_policy": OutputPolicy("ensemble_compact"),
            "material_parameters": base.material_parameters.model_copy(
                update={PROBE_PARAMETER: float(theta)}
            ),
        }
    )
    registry = DataRegistry.load(root, allowed_commodities=spec.commodities)
    import tempfile

    with tempfile.TemporaryDirectory(prefix="p05-abc-smoke-") as tmp:
        target = Path(tmp) / "run"
        manifest = run_material(spec, target, contract, registry, checkpoint_every=0)
        if manifest.status != "completed":
            raise RuntimeError(f"ABC smoke kernel run failed: {manifest.status}")
        import polars as pl

        accounts = pl.read_parquet(target / "national_accounts.parquet")
        return float(accounts["production"].sum())


def abc_synthetic_recovery(
    root: Path,
    *,
    config: Path,
    particles: int = 16,
    populations: int = 2,
    ticks: int = 4,
    households: int = 1000,
    scenario: str = "historical_f2_replay",
    truth: float = 0.9,
    seed: int = 1968,
) -> dict[str, Any]:
    """Run the declared ABC budget against a synthetic target from the same kernel."""
    if particles < 1 or populations < 1:
        raise ValueError("particles and populations must both be >= 1")
    config.read_text(encoding="utf-8")  # the declared control must be readable
    import pyabc

    observed_value = _summary_output(
        truth, root=root, ticks=ticks, households=households, scenario=scenario
    )

    def model(theta: Any) -> dict[str, float]:
        # pyabc passes a scalar for a one-parameter prior and a mapping otherwise
        value = float(theta) if not isinstance(theta, dict) else float(theta[PROBE_PARAMETER])
        return {
            "output": _summary_output(
                value, root=root, ticks=ticks, households=households, scenario=scenario
            )
        }

    # pyabc wants a Distribution container: a bare scalar distribution breaks
    # its history writer (py_parameter.items()), and a plain dict is refused
    prior = pyabc.Distribution({PROBE_PARAMETER: pyabc.RV("uniform", PROBE_LO, PROBE_HI)})
    from pyabc.sampler import SingleCoreSampler

    # one worker keeps the smoke deterministic and cheap (the plan asks for an
    # API proof, not a throughput measurement)
    abc = pyabc.ABCSMC(
        model,
        prior,
        population_size=pyabc.ConstantPopulationSize(particles),
        sampler=SingleCoreSampler(),
    )
    import tempfile

    with tempfile.TemporaryDirectory(prefix="p05-abc-db-") as tmp:
        db = pyabc.create_sqlite_db_id(file_=str(Path(tmp) / "abc.db"))
        abc.new(db, {"output": observed_value})
        history = abc.run(max_nr_populations=populations)
        completed = int(history.max_t) + 1
        # pyabc's m is the model index and t the generation
        posterior = history.get_distribution(m=0, t=history.max_t)
    # pyabc returns (frame, weights) here; older versions returned a bare frame
    # carrying its own weight column
    if isinstance(posterior, tuple):
        frame, weights = posterior
        weights = weights.astype(float)
    else:
        frame, weights = posterior, posterior["weight"].to_numpy(dtype=float)
    values = frame[PROBE_PARAMETER].to_numpy(dtype=float)
    posterior_mean = float((weights * values).sum() / weights.sum())

    return {
        "status": "ok",
        "command": "calibration abc-smoke",
        "kind": "synthetic_recovery",
        "parameter": PROBE_PARAMETER,
        "prior_support": [PROBE_LO, PROBE_HI],
        "truth": truth,
        "observed_summary": observed_value,
        "particles": particles,
        "populations_requested": populations,
        "populations_completed": completed,
        "seed": seed,
        "checkpoint_used": False,
        "posterior_mean": posterior_mean,
        "posterior_particles": int(values.size),
        "note": (
            "throwaway synthetic target produced by the same kernel; this is an API "
            "smoke only and is NOT historical-calibration evidence"
        ),
    }


def abc_registry_path(root: Path, *, config: Path) -> dict[str, Any]:
    """Prove the real registry path yields no candidate set."""
    screen = screen_parameters(root, config=config)
    return {
        "status": screen["status"],
        "command": "calibration abc-smoke",
        "kind": "real_registry_path",
        "identifiable_set": screen["identifiable_set"],
        "declared_linkage": screen["declared_linkage"],
        "inference_status": screen["inference_status"],
        "blocking_reasons": screen["blocking_reasons"],
        "note": "no candidate set exists, so no ABC run is started on the real registry",
    }
